function applyPageLanguage() {
  document.documentElement.lang = lang() === "en" ? "en" : "ta";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (!el.dataset.ta) el.dataset.ta = el.textContent.trim();
    const key = el.dataset.i18n;
    el.textContent = lang() === "en" && EN[key] ? EN[key] : el.dataset.ta;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    if (!el.dataset.altTa) el.dataset.altTa = el.getAttribute("alt") || "";
    const key = el.dataset.i18nAlt;
    el.alt = lang() === "en" && EN[key] ? EN[key] : el.dataset.altTa;
  });
  const title = lang() === "en" ? document.body.dataset.titleEn : document.body.dataset.titleTa;
  if (title) document.title = title;
}

function renderChrome() {
  const headerEl = document.getElementById("site-header");
  const footerEl = document.getElementById("site-footer");
  if (headerEl) {
    headerEl.className = "site-header";
    headerEl.innerHTML = header();
  }
  if (footerEl) {
    footerEl.className = "site-footer";
    footerEl.innerHTML = footer();
  }
  const memberLink = document.getElementById("member-form-link");
  const memberUrl = localStorage.getItem("hm-member-url");
  if (memberLink && memberUrl) memberLink.href = memberUrl;
  applyPageLanguage();
  bindChrome();
}

function bindChrome() {
  const toggle = document.querySelector(".nav-toggle");
  const nav = document.getElementById("site-nav");
  if (toggle && nav) {
    toggle.addEventListener("click", () => {
      const open = nav.classList.toggle("is-open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
    });
  }
  document.querySelectorAll(".nav-parent").forEach((button) => {
    button.addEventListener("click", () => {
      if (window.matchMedia("(max-width: 980px)").matches) {
        button.parentElement.classList.toggle("is-open");
      }
    });
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      localStorage.setItem("hm-lang", button.dataset.setLang);
      renderChrome();
      document.dispatchEvent(new Event("hm-lang"));
    });
  });
  const openSearch = document.getElementById("search-open");
  if (openSearch) openSearch.addEventListener("click", () => openSearchDialog());
}

function openSearchDialog() {
  let dialog = document.getElementById("search-dialog");
  if (!dialog) {
    dialog = document.createElement("div");
    dialog.id = "search-dialog";
    dialog.className = "search-dialog";
    dialog.innerHTML = `<div class="search-panel" role="dialog" aria-modal="true">
      <input id="search-input" type="search" placeholder="${lang() === "en" ? "Search pages" : "பக்கங்களைத் தேடுங்கள்"}">
      <ul class="search-list" id="search-list"></ul>
    </div>`;
    document.body.appendChild(dialog);
    dialog.addEventListener("click", (event) => {
      if (event.target === dialog) dialog.classList.remove("is-open");
    });
    dialog.querySelector("#search-input").addEventListener("input", (event) => {
      renderSearch(event.target.value);
    });
  }
  dialog.classList.add("is-open");
  const input = dialog.querySelector("#search-input");
  input.value = "";
  renderSearch("");
  input.focus();
}

function renderSearch(query) {
  const list = document.getElementById("search-list");
  const q = query.trim().toLowerCase();
  const hits = PAGES.filter((item) => {
    const blob = `${item.ta} ${item.en} ${item.taBlurb} ${item.enBlurb}`.toLowerCase();
    return !q || blob.includes(q);
  });
  list.innerHTML = hits.map((item) => {
    const title = lang() === "en" ? item.en : item.ta;
    const blurb = lang() === "en" ? item.enBlurb : item.taBlurb;
    return `<li><a href="${item.href}">${title}<small>${blurb}</small></a></li>`;
  }).join("");
}

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    document.getElementById("search-dialog")?.classList.remove("is-open");
    document.getElementById("site-nav")?.classList.remove("is-open");
  }
});

function escapeText(value) {
  return String(value ?? "").replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[ch]));
}

function renderNotices() {
  const section = document.getElementById("live-notices");
  const list = document.getElementById("notice-list");
  if (!section || !list) return;
  const notices = (window.HM_SERVER && window.HM_SERVER.notices) || [];
  if (!notices.length) {
    section.hidden = true;
    list.innerHTML = "";
    return;
  }
  const english = lang() === "en";
  list.innerHTML = notices.map((item) => {
    const title = escapeText(english && item.titleEn ? item.titleEn : item.titleTa);
    const body = escapeText(english && item.bodyEn ? item.bodyEn : item.bodyTa);
    const date = item.date ? `<time>${escapeText(item.date.split("-").reverse().join("."))}</time>` : "";
    return `<article class="notice-card"><h3>${title}</h3>${date}<p>${body}</p></article>`;
  }).join("");
  section.hidden = false;
}

function loadLive() {
  fetch("content.php", { cache: "no-store" })
    .then((response) => (response.ok ? response.json() : null))
    .then((data) => {
      if (!data || typeof data !== "object") return;
      window.HM_SERVER = data;
      renderNotices();
      renderNext();
      document.dispatchEvent(new Event("hm-live"));
    })
    .catch(() => {});
}

function renderNext() {
  const card = document.getElementById("next-pooja");
  if (!card || !window.HM) return;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const next = HM.poojaList()
    .filter((item) => !item.closed && new Date(`${item.date}T00:00:00`) >= today)
    .sort((a, b) => a.date.localeCompare(b.date))[0];
  if (!next) return;
  const months = lang() === "en"
    ? ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]
    : ["ஜனவரி", "பெப்ரவரி", "மார்ச்", "ஏப்ரில்", "மே", "ஜூன்", "ஜூலை", "ஆகஸ்ட்", "செப்ரெம்பர்", "அக்டோபர்", "நவம்பர்", "டிசெம்பர்"];
  const set = (key, value) => {
    const el = card.querySelector(`[data-next="${key}"]`);
    if (el) el.textContent = value;
  };
  set("day", String(Number(next.date.slice(8))));
  set("month", months[Number(next.date.slice(5, 7)) - 1]);
  set("year", next.date.slice(0, 4));
  set("name", next.name);
  set("sponsor", `${lang() === "en" ? "Sponsor" : "உபயதாரர்"} : ${next.sponsor}`);
}

